#!/usr/bin/env python3
"""Generate config/rgb_layers.dtsi: per-key LED colors for mode layers
(MoErgo PR36 "zmk,underglow-layer"). Colors are derived from the layers'
actual bindings, so re-run this after changing those layers:

    python3 tools/gen_rgb_layers.py config/glove80.keymap config/rgb_layers.dtsi
"""
import re
import sys

OFF = "___"
COLORS = {  # name -> 0xRRGGBB
    "GRN": 0x00FF40, "ORN": 0xFF7000, "CYN": 0x00C8FF, "RED": 0xFF0000,
    "BLU": 0x0030FF, "MAJ": 0xFF00C0, "AZU": 0x2060FF, "PUR": 0x9020FF,
}
HOME_ROW = [35, 36, 37, 38, 41, 42, 43, 44]


def layer_bindings(keymap: str, name: str) -> list[str]:
    i = keymap.index(f"layer_{name} {{")
    body = keymap[keymap.index("<", i) + 1: keymap.index(">;", i)]
    starts = [m.start() for m in re.finditer(r"&", body)]
    out = [body[a:b].strip() for a, b in zip(starts, starts[1:] + [len(body)])]
    assert len(out) == 80, (name, len(out))
    return out


def combo_positions(keymap: str, binding: str) -> list[int]:
    pos_names = dict(re.findall(r"#define (POS_\w+) (\d+)", keymap))
    for block in re.findall(r"\{[^{}]*\}", keymap):
        if f"bindings = <{binding}>" in block:
            names = re.search(r"key-positions = <([^>]*)>", block).group(1).split()
            return [int(pos_names.get(n, n)) for n in names]
    return []


def gaming(keymap: str) -> list[str]:
    move, abil = {"W", "A", "S", "D"}, set("QERFGTZXCV") | {f"N{i}" for i in range(1, 6)}
    mods, out = {"LSHFT", "RSHFT", "LCTRL", "RCTRL", "LALT", "RALT", "TAB", "SPACE"}, []
    for b in layer_bindings(keymap, "Gaming"):
        key = b.split()[1] if b.startswith("&kp ") else ""
        out.append("GRN" if key in move else "ORN" if key in abil else "CYN" if key in mods
                   else "RED" if key == "ESC" else "BLU" if key in ("RET", "ENTER") else OFF)
    for p in combo_positions(keymap, "&tog LAYER_Gaming"):   # how to get back out
        out[p] = "MAJ"
    return out


def home_row(color: str) -> list[str]:
    return [color if p in HOME_ROW else OFF for p in range(80)]


def node(name: str, colors: list[str]) -> str:
    rows = [(0, 10), (10, 22), (22, 34), (34, 46), (46, 64), (64, 80)]
    body = "\n".join("                " + " ".join(f"{c:>3}" for c in colors[a:b]) for a, b in rows)
    return (f"        {name}Leds {{\n            bindings = <\n{body}\n            >;\n"
            f"            layer-id = <LAYER_{name}>;\n        }};\n")


def main() -> None:
    keymap = open(sys.argv[1], encoding="utf-8").read()
    defs = "\n".join(f"#define {k} &ug 0x{v:06X}" for k, v in COLORS.items())
    out = (
        "// GENERATED by tools/gen_rgb_layers.py from config/glove80.keymap. Do not edit by hand.\n"
        "// Per-key LEDs for mode layers (requires MoErgo PR36 firmware, CONFIG_EXPERIMENTAL_RGB_LAYER).\n"
        "// Layers without an entry here keep the LEDs dark.\n\n"
        f"{defs}\n#define ___ &ug 0x000000\n\n"
        "/ {\n    underglow-layer {\n"
        + node("Gaming", gaming(keymap))
        + node("Typing", home_row("AZU"))
        + node("Autoshift", home_row("PUR"))
        + "    };\n};\n"
    )
    open(sys.argv[2], "w", encoding="utf-8").write(out)
    print(f"wrote {sys.argv[2]}")


if __name__ == "__main__":
    main()
